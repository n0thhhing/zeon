/// Table for Galois Field multiplication (GF(2^8))
pub const GF_MUL_TABLE: [256][256]u8 = blk: {
    var table: [256][256]u8 = undefined;
    @setEvalBranchQuota(1_000_000);

    for (0..256) |a| {
        for (0..256) |b| {
            var result: u8 = 0;
            var x: u8 = @intCast(a);
            var y: u8 = @intCast(b);
            while (y != 0) {
                result ^= (y & 1) * x;
                x = (x << 1) ^ ((x >> 7) * 0x1b);
                y >>= 1;
            }
            table[a][b] = result;
        }
    }

    break :blk table;
};

/// Gets the length of a vector
pub inline fn vecLen(comptime T: type) usize {
    const type_info = @typeInfo(T);
    comptime assert(type_info == .vector);
    return type_info.vector.len;
}

pub inline fn PromoteChild(comptime Child: type) type {
    return switch (Child) {
        i8 => i16,
        i16 => i32,
        i32 => i64,
        i64 => i128,
        u8 => u16,
        u16 => u32,
        u32 => u64,
        u64 => u128,
        f16 => f32,
        f32 => f64,
        else => @compileError("Cannot promote type " ++ @typeName(Child)),
    };
}

pub inline fn DemoteChild(comptime Child: type) type {
    return switch (Child) {
        i16 => i8,
        i32 => i16,
        i64 => i32,
        i128 => i64,
        u16 => u8,
        u32 => u16,
        u64 => u32,
        u128 => u64,
        f32 => f16,
        f64 => f32,
        else => @compileError("Cannot demote type " ++ @typeName(Child)),
    };
}

/// Promotes the Child type of the vector `T` to double bitwidth (e.g. i8 -> i16)
pub inline fn PromoteVector(comptime T: type) type {
    const len = vecLen(T);
    const Child = std.meta.Child(T);
    return @Vector(len, PromoteChild(Child));
}

/// Demotes the Child type of the vector `T` to half bitwidth (e.g. i16 -> i8)
pub inline fn DemoteVector(comptime T: type) type {
    const len = vecLen(T);
    const Child = std.meta.Child(T);
    return @Vector(len, DemoteChild(Child));
}

/// Joins two vectors into a wider vector
pub inline fn join(
    a: anytype,
    b: anytype,
) @Vector(
    vecLen(@TypeOf(a)) + vecLen(@TypeOf(b)),
    std.meta.Child(@TypeOf(a, b)),
) {
    const Child = std.meta.Child(@TypeOf(a));
    const a_len = comptime vecLen(@TypeOf(a));
    const b_len = comptime vecLen(@TypeOf(b));

    return @shuffle(
        Child,
        a,
        b,
        @as([a_len]i32, simd.iota(i32, a_len)) ++ @as([b_len]i32, ~simd.iota(i32, b_len)),
    );
}

/// Absolute difference between vectors
pub inline fn abdGeneric(a: anytype, b: anytype) @TypeOf(a, b) {
    const T = @TypeOf(a, b);
    const Child = std.meta.Child(T);
    const type_info = @typeInfo(Child);
    if (type_info == .int) {
        switch (type_info.int.signedness) {
            .unsigned => {
                const max_v: T = @max(a, b);
                const min_v: T = @min(a, b);
                return max_v - min_v;
            },
            .signed => {
                const P = comptime PromoteVector(T);
                const a_p: P = a;
                const b_p: P = b;
                const diff: P = a_p -% b_p;
                const abs_diff = @abs(diff);
                const abs_diff_signed: P = @bitCast(abs_diff);
                return @truncate(abs_diff_signed);
            },
        }
    } else {
        return @abs(a - b);
    }
}

/// Saturated addition for signed/unsigned integers
pub inline fn qaddGeneric(a: anytype, b: anytype) @TypeOf(a, b) {
    const T = @TypeOf(a, b);
    const Child = std.meta.Child(T);
    const min_val = std.math.minInt(Child);
    const max_val = std.math.maxInt(Child);

    var res: T = undefined;
    const len = comptime vecLen(T);
    inline for (0..len) |i| {
        const val_a: i128 = a[i];
        const val_b: i128 = b[i];
        const sum = val_a + val_b;
        if (sum > max_val) {
            res[i] = max_val;
        } else if (sum < min_val) {
            res[i] = min_val;
        } else {
            res[i] = @intCast(sum);
        }
    }
    return res;
}

/// Saturated subtraction for signed/unsigned integers
pub inline fn qsubGeneric(a: anytype, b: anytype) @TypeOf(a, b) {
    const T = @TypeOf(a, b);
    const Child = std.meta.Child(T);
    const min_val = std.math.minInt(Child);
    const max_val = std.math.maxInt(Child);

    var res: T = undefined;
    const len = comptime vecLen(T);
    inline for (0..len) |i| {
        const val_a: i128 = a[i];
        const val_b: i128 = b[i];
        const diff = val_a - val_b;
        if (diff > max_val) {
            res[i] = max_val;
        } else if (diff < min_val) {
            res[i] = min_val;
        } else {
            res[i] = @intCast(diff);
        }
    }
    return res;
}

test "common helpers" {
    const v: @Vector(8, u8) = @splat(1);
    try expectEqual(8, vecLen(@TypeOf(v)));
    try expectEqual(@Vector(8, u16), PromoteVector(@TypeOf(v)));

    const a: @Vector(4, i16) = .{ 10, -20, 30, -40 };
    const b: @Vector(4, i16) = .{ 5, 20, -30, 40 };
    const diff = abdGeneric(a, b);
    try expectEqual(@Vector(4, i16){ 5, 40, 60, 80 }, diff);
}
