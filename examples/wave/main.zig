test "render4 is deterministic" {
    const fx: [LANES]f32 = .{
        -0.8,
        -0.2,
        0.2,
        0.8,
    };

    var r1: [LANES]f32 = undefined;
    var g1: [LANES]f32 = undefined;
    var b1: [LANES]f32 = undefined;

    var r2: [LANES]f32 = undefined;
    var g2: [LANES]f32 = undefined;
    var b2: [LANES]f32 = undefined;

    render4(
        &fx,
        0.35,
        2.0,
        &r1,
        &g1,
        &b1,
    );

    render4(
        &fx,
        0.35,
        2.0,
        &r2,
        &g2,
